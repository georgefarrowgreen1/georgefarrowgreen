/* ---------- the world in quarter-degrees, named ----------
   Every 0.25° square, named the way the map names somewhere (placeName in
   functions/_where.js, asked about the square's middle), so the passport can
   name hundreds of points along a flight for next to nothing. The names live
   in functions/_placegrid.data.js, generated from the map's own coastline and
   lists. After changing pigeon/land.js or pigeon/countries.js, regenerate it:

   node --input-type=module -e "import fs from 'node:fs'; import { placeName } from './functions/_where.js'; import { gridFile } from './functions/_placegrid.js'; fs.writeFileSync('functions/_placegrid.data.js', gridFile(placeName))"

   Rows run north to south, squares west to east from 180°W. A row is runs of
   "name (its index, base 36).how many (base 36, when more than one)". */
import { STEP, NAMES, DATA } from "./_placegrid.data.js";

const W = Math.round(360 / STEP), H = Math.round(180 / STEP);
let rows = null;
const cache = new Map();
function row(r) {
  let a = cache.get(r);
  if (a) return a;
  rows ||= DATA.split(";");
  a = new Uint8Array(W);
  let c = 0;
  for (const run of rows[r].split(",")) { const [i, n] = run.split("."); const v = parseInt(i, 36), k = n ? parseInt(n, 36) : 1; a.fill(v, c, c + k); c += k; }
  cache.set(r, a);
  return a;
}
// the place at a point ("France", "the North Sea", "the South Pacific")
export function placeAt(lat, lon) {
  const r = Math.min(H - 1, Math.max(0, Math.floor((90 - lat) / STEP)));
  const c = ((Math.floor((lon + 180) / STEP) % W) + W) % W;
  return NAMES[row(r)[c]];
}
// The data file, made by asking placeName about every square
export function gridFile(placeName, step = STEP) {
  const w = Math.round(360 / step), h = Math.round(180 / step), names = [], idx = new Map(), out = [];
  const id = (n) => { if (!idx.has(n)) { idx.set(n, names.length); names.push(n); } return idx.get(n); };
  const run = (v, n) => v.toString(36) + (n > 1 ? "." + n.toString(36) : "");
  for (let r = 0; r < h; r++) {
    const lat = 90 - (r + 0.5) * step, runs = [];
    let cur = -1, len = 0;
    for (let c = 0; c < w; c++) {
      const v = id(placeName(lat, -180 + (c + 0.5) * step));
      if (v === cur) len++; else { if (len) runs.push(run(cur, len)); cur = v; len = 1; }
    }
    runs.push(run(cur, len)); out.push(runs.join(","));
  }
  return `// Generated by gridFile in functions/_placegrid.js: don't edit by hand.\nexport const STEP = ${step};\nexport const NAMES = ${JSON.stringify(names)};\nexport const DATA = ${JSON.stringify(out.join(";"))};\n`;
}
