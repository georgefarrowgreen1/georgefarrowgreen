// InFlite's menu, shared: .tools/inflite/menu.js (with the apps' icons, .tools/inflite/icons/, drawn into it) copied
// into each app's script, and .tools/inflite/menu.css into its stylesheet, each between the marks below (so each app
// still sends the files it did, as its service worker and version check expect). Change them there, then run:
// node .tools/iflmenu.mjs   (and for Mail and Today, in the inflite repo, each folder named:
// node .tools/iflmenu.mjs ../inflite/email/public ../inflite/today/public)
// A unit test checks this repository's copies (unit/iflmenu.test.mjs).
import { readFileSync, writeFileSync, existsSync } from "fs";
const ROOT = new URL("../", import.meta.url).pathname;
export const JS_START = "// ==== InFlite's menu, shared: from .tools/inflite/menu.js by node .tools/iflmenu.mjs (change it there) ====";
export const JS_END = "// ==== end of InFlite's menu ====";
export const CSS_START = "/* ==== InFlite's menu, shared: from .tools/inflite/menu.css by node .tools/iflmenu.mjs (change it there) ==== */";
export const CSS_END = "/* ==== end of InFlite's menu ==== */";
export const SCRIPTS = ["pigeon/app.js", "weather/app.js", "fitness/app.js", "markets/app.js", "account/app.js"];
export const STYLES = ["pigeon/styles.css", "weather/styles.css", "fitness/styles.css", "markets/styles.css", "account/styles.css"];
const APPS = ["chat", "weather", "fitness", "markets", "mail", "account"];
// (an app in no other app's menu, its name, icon and colour in its own copy alone: Today, at inflite.ai, its folder
// named today/public)
const OWN = { today: { name: "Today", tint: "var(--ifl-accent-ink)" } };
const ownOf = (dir) => Object.keys(OWN).find((a) => new RegExp(`(^|/)${a}/public/?$`).test(dir)) || null;

// an app's icon, small: no notes, no spaces between its parts
const mini = (s) => s.replace(/<!--[\s\S]*?-->/g, "").replace(/<\?xml[^>]*>/, "").replace(/>\s+</g, "><").replace(/\s{2,}/g, " ").trim();
export const jsBlock = (own) => {
  const icons = Object.fromEntries([...APPS, ...(own ? [own] : [])].map((a) => [a, mini(readFileSync(`${ROOT}.tools/inflite/icons/${a}.svg`, "utf8"))]));
  let js = readFileSync(`${ROOT}.tools/inflite/menu.js`, "utf8").trim().replace("/*ICONS*/{}", JSON.stringify(icons));
  if (own) {
    const last = '["account", "Account"]];';
    if (!js.includes(last)) throw new Error(`.tools/inflite/menu.js's APPS no longer ends ${last}: say in iflmenu.mjs where ${own} goes`);
    js = js.replace(last, `["account", "Account"], ["${own}", "${OWN[own].name}"]];`);
  }
  return `${JS_START}\n${js}\n${JS_END}`;
};
export const cssBlock = (own) => `${CSS_START}\n${readFileSync(`${ROOT}.tools/inflite/menu.css`, "utf8").trim()}\n${readFileSync(`${ROOT}.tools/inflite/tokens.css`, "utf8").trim()}\n${readFileSync(`${ROOT}.tools/inflite/design.css`, "utf8").trim()}${own ? `\n.ifm-in-${own} { --ifm-tint: ${OWN[own].tint}; }` : ""}\n${CSS_END}`;
export const TOKENS_START = "/* ==== InFlite design tokens: generated by .tools/iflmenu.mjs ==== */";
export const TOKENS_END = "/* ==== end of InFlite design tokens ==== */";
export const tokensBlock = () => `${TOKENS_START}\n${readFileSync(`${ROOT}.tools/inflite/tokens.css`, "utf8").trim()}\n${TOKENS_END}`;

function into(file, start, end, b) {
  const text = readFileSync(file, "utf8");
  const i = text.indexOf(start), j = text.indexOf(end);
  // (the script's copy goes where its marks are put, before anything that runs uses it; the stylesheet's at its foot)
  if (!(i >= 0 && j > i) && start === JS_START) throw new Error(`${file} has no marks for InFlite's menu: put them in, where it's to go`);
  const out = i >= 0 && j > i ? text.slice(0, i) + b + text.slice(j + end.length) : `${text.trimEnd()}\n\n${b}\n`;
  if (out !== text) writeFileSync(file, out);
  return out !== text;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const said = [], js = jsBlock(), css = cssBlock();
  for (const f of SCRIPTS) if (into(ROOT + f, JS_START, JS_END, js)) said.push(f);
  for (const f of STYLES) if (into(ROOT + f, CSS_START, CSS_END, css)) said.push(f);
  for (const f of ["styles.css", "status/styles.css", "fitting/styles.css"]) if (into(ROOT + f, TOKENS_START, TOKENS_END, tokensBlock())) said.push(f);
  // (the other folders named, each an app's of its own: Mail's and Today's, in the inflite repo)
  for (const dir of process.argv.slice(2)) {
    if (!existsSync(`${dir}/app.css`)) throw new Error(`No app.css in ${dir}`);
    const own = ownOf(dir);
    if (into(`${dir}/app.js`, JS_START, JS_END, own ? jsBlock(own) : js)) said.push(`${dir}/app.js`);
    if (into(`${dir}/app.css`, CSS_START, CSS_END, own ? cssBlock(own) : css)) said.push(`${dir}/app.css`);
  }
  console.log(said.length ? `InFlite's menu, copied into: ${said.join(", ")}` : "InFlite's menu: every copy already the same");
}
