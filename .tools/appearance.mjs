// Bundle before-paint Appearance without adding a dependency or network request.
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
const root=new URL('../',import.meta.url).pathname;
const start='// ==== InFlite Appearance: generated by .tools/appearance.mjs ====',end='// ==== End InFlite Appearance ====';
const block=`${start}\n${readFileSync(root+'.tools/inflite/appearance.js','utf8').trim()}\n${end}`;
export function bundle(file){
  let s=existsSync(file)?readFileSync(file,'utf8'):'';
  const a=s.indexOf(start),b=s.indexOf(end);
  s=a>=0&&b>a?s.slice(0,a)+block+s.slice(b+end.length):s.trimEnd()+'\n\n'+block+'\n';
  writeFileSync(file,s);
}
if(import.meta.url===`file://${process.argv[1]}`){
  for(const file of ['account/theme.js','fitness/theme.js','markets/theme.js','pigeon/theme.js','weather/early.js','status/theme.js',...process.argv.slice(2)])bundle(root+file);
}
